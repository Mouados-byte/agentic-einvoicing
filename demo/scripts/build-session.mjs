// Turns the captured terminal output in session/*.txt into src/session.ts for the composition.
import { readFileSync, writeFileSync } from 'node:fs';
const read = (f) => readFileSync(new URL(`../session/${f}`, import.meta.url), 'utf8').replace(/\s+$/, '');
const up = read('make-up.txt').split('\n');
const data = {
  setupSteps: up.filter((l) => (l.startsWith('==>') && !l.includes('Smoke eval')) || l.startsWith('✓')),
  agents: read('agents.txt'),
  tools: read('tools.txt'),
  teamQuery: read('team-query.txt'),
  injectedLine: read('injected-line.txt'),
  invoiceCheck: read('invoice-check.txt'),
  evals: up.filter((l) => /^(PASS|FAIL)|passed$/.test(l)).join('\n'),
  queries: read('queries.txt'),
};
writeFileSync(new URL('../src/session.ts', import.meta.url),
  `// Generated by scripts/build-session.mjs from session/*.txt (real captured output). Do not edit.\nexport const session = ${JSON.stringify(data, null, 2)} as const;\n`);
console.log(Object.fromEntries(Object.entries(data).map(([k, v]) => [k, (Array.isArray(v) ? v.join('\n') : v).split('\n').length])));
